"""Battery #3 maker-mode re-gate of killed candidates (manifest 2026-08-19).

v2 (final-review fix wave, 2026-08-19): the v1 run tested the wrong bar for
5 of 6 candidates (C1) and charged Gate 2 at taker cost inside a maker
re-gate (H2). Both are fixed here; see `_CANDIDATE_ENTRY_BASIS` and
`_maker_regate_round_trip_bps`. v1 artifacts (verdict docs, trades CSVs,
ledger rows) are RETAINED, never deleted or overwritten — every v2 artifact
carries a `_v2` suffix distinct from v1's names, per manifest Amendment 3.

For each of the 6 manifest re-gate items — xs_momentum, lf_trend,
funding_carry, pairs_statarb, vol_breakout, baseline_rsi_ema — trades are
regenerated by the UNCHANGED candidate module (the module code that
already produced a REJECT is never touched), passed through
`edge_lab.maker_fill.apply_maker_fill` to drop entries that would not
actually have filled as a resting limit order, then screened at Gate 1
under the M1 cost model (maker fee, no slippage, on the entry leg; taker
fee + slippage on the exit leg — the conservative, costs-only-go-up
approximation of the manifest's mixed taker-stop/maker-TP exit rule). A
Gate 1 PASS proceeds to Gate 2, scored under the SAME cost model (H2) —
the two gates must not disagree about what a trade costs. `screen.py` and
`run_battery.py`'s own taker-cost Gate 2 path are never modified; this
runner computes its own Gate 1 ratio and its own Gate 2 cost map,
substituting into `gate2.daily_returns_from_trades`/`gate2.run_gate2` (the
actual statistical machinery), which are reused unchanged.

Representative-variant rule (decided BEFORE any maker-mode result was
observed, so it cannot be data-mined post-hoc): for the 4 candidates with
more than one pre-registered variant, this runner re-gates the ONE variant
with the highest recorded `ratio_taker` in that candidate's most recent
verdict (`.planning/evidence/killtests/<candidate>-verdict-20260818.json`)
— the variant closest to clearing Gate 1 under taker costs is the one
where a pure cost-model artifact would show up, which is exactly the
question B3 asks. vol_breakout has only one variant, so there is no
choice to make. See `_MAKER_REGATE_VARIANT` for the recorded picks and
their source ratios.

baseline_rsi_ema (manifest item #8) has no prior edge_lab variant to draw
from — the module the RSI9/EMA20 baseline was never a candidate. Its
trades are regenerated fresh via `audit._harness` (`baseline_strategy` +
`make_engine`) over the full clean-epoch h1 history of the 5 majors
(BTC/ETH/SOL/BNB/ADA), then filtered to entries at or after the manifest's
clean-data epoch (2026-04-25) — the pre-epoch bars are still fed to the
engine for indicator warm-up, per the manifest's Amendment 1(c). This is a
DIFFERENT run from the already-executed 2026-08-19 3-fold walk-forward
baseline (commit `2afbbd3`, `backtesting/results/
wf_baseline_fixed_engine_2026-08-19.txt`): that run is recorded in the
ledger separately as `baseline_rsi_ema_walkforward_taker` by
`record_walkforward_baseline_trial` (idempotent — m1 fix), is NOT
re-executed by this module, and must never be confused with this module's
own `baseline_rsi_ema` maker-regate trial.

baseline_rsi_ema's trades come from `audit._harness.load_candles` (the
FULL raw CSV), while the `bars` frame passed to `apply_maker_fill` is
`bundle["h1"]` (cut at `now_ms` by `run_battery.load_bundle`'s closed-bar
rule). A trade whose entry bar falls outside that cut is scored as a
missed fill rather than silently matched against a bar that would not
actually have been "closed" data at battery time — the conservative
direction, not a defect.

Crash isolation matches `run_battery`: one candidate's exception becomes
its ERROR verdict (doc + ledger row still written) and the loop continues.
Every run appends exactly one trial-ledger row per candidate, whatever the
outcome — NO_TRADES-after-fill and Gate-1 KILL included, not just PASS.
"""

