def record_walkforward_baseline_trial(date_str: str) -> dict | None:
    """Ledger the ALREADY-EXECUTED 2026-08-19 walk-forward baseline
    (commit 2afbbd3) as its own trial, per manifest Amendment 1(a): it is
    a genuinely new executed trial, counted before this battery's 8
    additions, and must never share a ledger row with variant #8's maker
    re-gate of the same underlying strategy. This function only records
    that the trial happened — it does not call the engine.

    Idempotent (final-review m1): every prior call already appended this
    exact (candidate, variant) pair, so a re-invocation (e.g. re-running
    the v2 re-gate) must not silently duplicate it — raw-vs-distinct
    ledger divergence is a live concern per Amendment 2(e).
    """
    key = ("baseline_rsi_ema", "baseline_rsi_ema_walkforward_taker")
    existing = trial_ledger.load_entries()
    if any((e.get("candidate"), e.get("variant")) == key for e in existing):
        logger.info("%s/%s already ledgered — skipping duplicate append", *key)
        return None
    entry = {
        "candidate": key[0],
        "variant": key[1],
        "params": {
            "engine": "make_engine() defaults (bybit_perp fees, atr_aware slippage, funding on)",
            "folds": "3",
            "epoch": "clean epoch 2026-04-25..2026-08-06",
        },
        "date": date_str,
        "gate1_verdict": "N/A - walk-forward IS/OOS/DSR gate, not edge_lab screen_trades",
        "gate2_passed": False,  # 5/5 symbols GATE REJECT, DSR 0.000 every symbol
        "source": str(WALKFORWARD_BASELINE_RESULT),
    }
    trial_ledger.append_entries([entry])
    return entry


